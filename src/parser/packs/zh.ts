/**
 * Words with a numeral in them that are not amounts: "一共" (in all), "二手" (second-hand),
 * "一块儿" (together), Traditional weekdays, and a small count before a measure word
 * ("一箱牛奶", "两袋米", "三双袜子"), which is how many, not how much. Kept as written.
 * The measure words leave out 块/元/毛/角 (money) and 个/天/周/月/年 (date phrases need the digit).
 */
const NOT_AMOUNTS = /(?:一共|一起|二手|统一|統一|一般|一定|一切|一律|一旦|一边|一邊|一块儿|一塊兒|一块去|一塊去|(?:禮拜|週)[一二三四五六日天]|[一二两兩三四五六七八九十百千几幾]+(?=[箱袋盒斤束双雙条條支只隻把台套趟桶罐碗盘盤串间間本部辆輛副对對片根粒颗顆位家件杯份顿頓张張瓶次场場桌]|包(?!邮|郵)))/gu;

function numberWords(text: string): string {
  const kept: string[] = [];
  text = text.replace(NOT_AMOUNTS, (m) => { kept.push(m); return String.fromCharCode(0xe000 + kept.length - 1); });
  let t = cjkNumeralsToDigits(expandK(text.replace(/(\d),(\d{3})(?!\d)/g, '$1$2')));
  // "12块5" / "十二块五毛" -> 12.5块
  t = t.replace(/(\d+)(块钱|塊錢|块|塊|元)(\d)(?:毛|角)?(?!\d)/g, '$1.$3$2');
  t = t.replace(/(\d+)\s?(块|元)\s?(\d)\s?(?:毛|角)/g, '$1.$3$2');
  return t.replace(/[\ue000-\ue0ff]/gu, (c) => kept[c.charCodeAt(0) - 0xe000] ?? c);
}

